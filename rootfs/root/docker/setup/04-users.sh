# Set bash options
set -eo pipefail
if [ "$DEBUGGER" = "on" ]; then
  echo "Enabling debugging"
  set -x$DEBUGGER_OPTIONS
fi
# - - - - - - - - - - - - - - - - - - - - - - - - -
# Set env variables
exitCode=0

# - - - - - - - - - - - - - - - - - - - - - - - - -
# Predefined actions

# - - - - - - - - - - - - - - - - - - - - - - - - -
# Main script
addgroup -S -g 1000 taiga 2>/dev/null || true
adduser -S -D -H -u 1000 -G taiga -h /usr/local/share/taiga -s /sbin/nologin taiga 2>/dev/null || true
grep -q "^taiga:" /etc/passwd
mkdir -p /usr/local/share/taiga /opt/taiga /data/taiga /config/taiga

# - - - - - - - - - - - - - - - - - - - - - - - - -
# Set the exit code
exitCode=$?
# - - - - - - - - - - - - - - - - - - - - - - - - -
